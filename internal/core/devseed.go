// addDevice creates a device and registers its LAN ip.
func (w *World) addDevice(id, hostname, profile, owner string, os OSInfo, hw Hardware, lanIP string) *Device {
	d := &Device{
		W: w, ID: id, Hostname: hostname, Profile: profile, Owner: owner,
		OS: os, HW: hw, FS: NewVFS(), Users: map[string]*User{},
		Services: map[string]*Service{}, Boot: w.Started.Add(-36 * time.Hour),
		PowerOK: true, NetUp: true, DHCPL: map[string]Lease{}, Installed: map[string]*VPkg{},
		Fail2Ban: map[string]int{}, Sessions: map[string]*TermSession{},
	}
	if lanIP != "" {
		cidr := lanIP[:len(lanIP)-len(lastOctet(lanIP))-1] + ".0/24"
		d.Ifaces = []*Iface{{Name: "eth0", IP: lanIP, CIDR: cidr, MAC: macFor(id), Zone: "lan", Up: true, Mode: "static"}}
		w.IPMap[lanIP] = id
	}
	w.Devices[id] = d
	w.Order = append(w.Order, id)
	return d
}

func lastOctet(ip string) string {
	for i := len(ip) - 1; i >= 0; i-- {
		if ip[i] == '.' {
			return ip[i+1:]
		}
	}
	return ip
}

func macFor(seed string) string {
	const hex = "0123456789ABCDEF"
	h := uint32(2166136261)
	for i := 0; i < len(seed); i++ {
		h ^= uint32(seed[i])
		h *= 16777619
	}
	b := "52:54:00:"
	for i := 0; i < 3; i++ {
		b += string(hex[(h>>uint(i*4))&0xF]) + string(hex[(h>>uint(i*4+2))&0xF])
		if i < 2 {
			b += ":"
		}
	}
	return b
}

// seedFS lays down the files a real box of this type would have.
