	v.Write("/etc/os-release", fmt.Sprintf("NAME=\"%s\"\nVERSION=\"%s\"\nID=%s\nVERSION_ID=\"%s\"\n", d.OS.Distro, d.OS.Ver, strings.ToLower(d.OS.Distro), d.OS.Ver), 0644, "root", "root")
